pub const MASCOT_ASCII: &str = r#"
               #+++++++++++++++
           #+++++++++++++++++++++++
        %++++++++#%%%%#*=:-=++*++++++#
      %+++++++#%%########=...:-=*#+++++%
     ++++++++**##########%-...:::-#%+++++
    ++++++#*--*###########+........*@%++++
   ++++++#=:=#####%######%=.....-*=.%#%#+++
  #+++++#-:=######%###%%%*......=%#.=@#%#++%
  +++++#:-:+#####%%##%%%*...........*%#**#++
  ++++#::...#####%#=-:............-**-=--#++
  +++%:.....#####@-.....:::..-=+==**=----=%+
  ++%+.....#####%#+=:-=-:..+#====:..+*----*%
  %++#:....###%%*-:..:....:*#=:..*#+*#-==+%
   #++++===*%#+-:......*=-:.:+@%%%+:.+%*++#
    #+++#@%##**-......%=....:*@##@#:..++++
     *:=@#####%#....-*#....*@#-..-#@*..%#
    *..=%**####-.....=#...%%-......-%*.#
    *..:%-:--:........*+.#+.........:**
     *-:+%=::.........+@++.........:-*
           *+=:::::::-+   *+=----=+*
"#;

pub fn print_mascot_banner() {
    const GREEN: &str = "\x1b[38;2;82;196;64m";
    const WHITE: &str = "\x1b[97m";
    const RESET: &str = "\x1b[0m";
    for line in MASCOT_ASCII.lines() {
        if line.is_empty() {
            continue;
        }
        let mut out = String::with_capacity(line.len() * 2);
        for ch in line.chars() {
            match ch {
                '+' => {
                    out.push_str(GREEN);
                    out.push(ch);
                }
                '.' | ':' | '-' | '=' => {
                    out.push_str(WHITE);
                    out.push(ch);
                }
                _ => {
                    out.push_str(RESET);
                    out.push(ch);
                }
            }
        }
        out.push_str(RESET);
        println!("{out}");
    }
    println!("{GREEN}PercyScarlett v0.1.0{RESET} — Clean-Room Rust Scarlett Bring-Up Layer");
}
